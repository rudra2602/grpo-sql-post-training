"""
Reward computation engine for GRPO text-to-SQL post-training.

Implements a 3-tier composite reward:
  - Tier 1: Format Adherence (+0.1) for valid markdown ```sql ... ``` code blocks.
  - Tier 2: Syntax & Executability (+0.2) for error-free sandbox execution on valid tables.
  - Tier 3: Execution Match (+0.7) for multiset row equivalence against gold output.

Includes anti-hacking guards against empty result exploitation, trivial scalar queries,
and unauthorized mutations.
"""

from collections import Counter
from pathlib import Path
import re
import sqlite3
import sys
from typing import Any, List, Optional, Set, Tuple, Union

# Ensure project root is in sys.path
ROOT_DIR = str(Path(__file__).resolve().parent.parent)
if ROOT_DIR not in sys.path:
    sys.path.insert(0, ROOT_DIR)

from src.executor import SafeSQLExecutor

FORMAT_REWARD = 0.1
SYNTAX_REWARD = 0.2
EXEC_MATCH_REWARD = 0.7

ORDER_BY_REGEX = re.compile(r"\bORDER\s+BY\b", re.IGNORECASE)
TABLE_REF_REGEX = re.compile(r"\b(?:FROM|JOIN)\s+[\"`']?([a-zA-Z0-9_]+)[\"`']?", re.IGNORECASE)
SQL_BLOCK_REGEX = re.compile(r"```(?:sql)?\s*(.*?)\s*```", re.DOTALL | re.IGNORECASE)


def extract_sql_query(text: Any) -> Tuple[str, bool]:
    """
    Extract SQL query string from model completion.
    Gracefully handles raw strings, chat formatted dicts, or lists of message dicts from TRL.

    Returns:
        Tuple of (cleaned_sql, has_markdown_fence).
    """
    if isinstance(text, list):
        if len(text) > 0 and isinstance(text[0], dict) and "content" in text[0]:
            text = text[0]["content"]
        elif len(text) > 0 and isinstance(text[0], str):
            text = text[0]
        else:
            text = str(text)
    elif isinstance(text, dict):
        text = text.get("content", str(text))

    if not isinstance(text, str) or not text.strip():
        return "", False

    match = SQL_BLOCK_REGEX.search(text)
    if match:
        sql = match.group(1).strip()
        return sql, True

    return text.strip(), False


def get_db_table_names(db_path: Union[str, Path, sqlite3.Connection]) -> Set[str]:
    """Query SQLite schema to extract all user table names."""
    query = "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%';"
    success, rows, _ = SafeSQLExecutor.execute(db_path, query)
    if success and rows:
        return {str(r[0]).lower() for r in rows}
    return set()


def extract_referenced_tables(sql: str) -> Set[str]:
    """Extract table names referenced in FROM and JOIN clauses."""
    matches = TABLE_REF_REGEX.findall(sql)
    return {m.lower() for m in matches}


def normalize_value(val: Any) -> Any:
    """Normalize a single SQL column value for robust equality matching."""
    if val is None:
        return None
    if isinstance(val, float):
        return round(val, 4)
    if isinstance(val, int):
        return val
    if isinstance(val, (bytes, bytearray)):
        return val.decode("utf-8", errors="ignore").strip().lower()
    return str(val).strip().lower()


def normalize_rows(rows: List[Tuple[Any, ...]]) -> List[Tuple[Any, ...]]:
    """Normalize all rows and cell values in a result set."""
    return [tuple(normalize_value(v) for v in row) for row in rows]


def check_result_equivalence(
    pred_rows: List[Tuple[Any, ...]],
    gold_rows: List[Tuple[Any, ...]],
    gold_sql: str
) -> bool:
    """
    Check equivalence between predicted and gold rows.
    Uses multiset (Counter) equivalence by default, and strict ordered list
    equivalence if ORDER BY is present in the gold query.
    """
    norm_pred = normalize_rows(pred_rows)
    norm_gold = normalize_rows(gold_rows)

    # Strict ordered check if ORDER BY is explicitly in gold query
    if ORDER_BY_REGEX.search(gold_sql):
        return norm_pred == norm_gold

    # Order-invariant multiset comparison
    return Counter(norm_pred) == Counter(norm_gold)


def compute_sql_reward(
    predicted_text: str,
    gold_sql: str,
    db_path: Union[str, Path, sqlite3.Connection],
    reward_mode: str = "tiered"
) -> float:
    """
    Compute verifiable SQLite execution reward for a model completion.

    Args:
        predicted_text: The raw output text generated by the model.
        gold_sql: The ground-truth reference SQL query.
        db_path: Path to the SQLite database file or connection.
        reward_mode: 'tiered' (default: +0.1/+0.2/+0.7) or 'binary' (+1.0 / 0.0).

    Returns:
        Scalar reward float between 0.0 and 1.0.
    """
    r_format = 0.0
    r_syntax = 0.0
    r_exec_match = 0.0

    # 1. Format extraction check
    pred_sql, has_markdown = extract_sql_query(predicted_text)
    if not pred_sql:
        return 0.0

    if has_markdown:
        r_format = FORMAT_REWARD

    # 2. Anti-Hacking Guard: Trivial scalar queries lacking valid table references
    valid_tables = get_db_table_names(db_path)
    referenced_tables = extract_referenced_tables(pred_sql)

    # A valid query must reference at least one existing table in the database
    if valid_tables and not (referenced_tables & valid_tables):
        # Query did not reference any real tables in the database (e.g. 'SELECT 1;')
        return r_format

    # 3. Syntax & Executability check via SafeSQLExecutor
    pred_success, pred_rows, _ = SafeSQLExecutor.execute(db_path, pred_sql)
    if not pred_success:
        return r_format

    r_syntax = SYNTAX_REWARD

    # 4. Gold query execution
    gold_success, gold_rows, _ = SafeSQLExecutor.execute(db_path, gold_sql)
    if not gold_success:
        # If the reference query failed, cannot award match points
        return r_format + r_syntax

    # 5. Anti-Hacking Guard: Empty result matching
    # If gold returns rows, an empty predicted result is not an execution match
    if len(gold_rows) > 0 and len(pred_rows) == 0:
        r_exec_match = 0.0
    elif len(gold_rows) == 0 and len(pred_rows) == 0:
        # Both returned empty: require schema table overlap
        gold_tables = extract_referenced_tables(gold_sql)
        if referenced_tables & gold_tables:
            r_exec_match = EXEC_MATCH_REWARD
        else:
            r_exec_match = 0.0
    else:
        # Both returned rows: check multiset equivalence
        if check_result_equivalence(pred_rows, gold_rows, gold_sql):
            r_exec_match = EXEC_MATCH_REWARD

    # 6. Compute final score
    if reward_mode == "binary":
        # Binary mode for ablation: requires execution match (1.0 or 0.0)
        return 1.0 if r_exec_match > 0.0 else 0.0

    total = r_format + r_syntax + r_exec_match
    return round(total, 4)


def grpo_sql_reward_func(
    completions: List[Any],
    gold_sql: List[str],
    db_path: List[Union[str, Path, sqlite3.Connection]],
    reward_mode: str = "tiered",
    **kwargs: Any
) -> List[float]:
    """
    TRL GRPOTrainer batch reward callable.
    Computes rewards across a batch of candidate rollout completions.
    """
    # Defensive alignment: Ensure gold_sql and db_path match completions count
    if len(gold_sql) > 0 and len(completions) > len(gold_sql) and len(completions) % len(gold_sql) == 0:
        multiplier = len(completions) // len(gold_sql)
        gold_sql = [g for g in gold_sql for _ in range(multiplier)]
        db_path = [d for d in db_path for _ in range(multiplier)]

    rewards: List[float] = []
    for pred, gold, db in zip(completions, gold_sql, db_path):
        r = compute_sql_reward(pred, gold, db, reward_mode=reward_mode)
        rewards.append(r)
    return rewards
